#!/usr/bin/env python3
"""Import metadata only from a byte-matching, pinned zeldaret/tmc EU build."""
import argparse
import bisect
import hashlib
import json
import pathlib
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHA1 = "cff199b36ff173fb6faf152653d1bccf87c26fb7"
REVISION = "5ab63f00e522ff69c5bc987e379f0163943f2833"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--tmc", type=pathlib.Path, default=ROOT / "third_party/tmc")
    p.add_argument("--out", type=pathlib.Path, default=ROOT / "symbols/eu")
    a = p.parse_args()
    tmc = a.tmc.resolve()
    revision = subprocess.check_output(["git", "-C", str(tmc), "rev-parse", "HEAD"], text=True).strip()
    if revision != REVISION:
        raise ValueError("EU metadata requires the pinned tmc revision")
    rom = tmc / "tmc_eu.gba"
    if hashlib.sha1(rom.read_bytes()).hexdigest() != SHA1:
        raise ValueError("tmc EU build is not byte-identical to the supported ROM")
    syms = subprocess.check_output(["readelf", "-sW", str(tmc / "tmc_eu.elf")], text=True)
    sections = subprocess.check_output(["readelf", "-SW", str(tmc / "tmc_eu.elf")], text=True)
    names, mappings = {}, {}
    for line in syms.splitlines():
        fields = line.split()
        if len(fields) != 8 or not fields[0].endswith(":") or not fields[0][:-1].isdigit():
            continue
        address, name = int(fields[1], 16), fields[7]
        names[name] = (address, int(fields[2]))
        if name.split(".")[0] in {"$a", "$t", "$d"}:
            mappings[address] = name[1]
    starts = sorted(mappings)
    copies = [(names["SoundMainRAM_Buffer"][0], names["SoundMainRAM"][0] & ~1, 0x380, "sound_main_ram"),
              (names["ram_sub_080B197C"][0], names["sub_080B197C"][0],
               names["RAMFUNCS_END"][0] - names["sub_080B197C"][0], "iwram_funcs")]
    a.out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as temporary:
        temp = pathlib.Path(temporary)
        (temp / "syms").write_text(syms)
        (temp / "sections").write_text(sections)
        subprocess.run(["python3", str(ROOT / "gbarecomp/tools/symbol_import/import_decomp_symbols.py"),
                        "--id", "minishcap_eu", "--name", "The Legend of Zelda: The Minish Cap (Europe)",
                        "--syms", str(temp / "syms"), "--sections", str(temp / "sections"),
                        "--map", str(tmc / "build/EU/tmc_eu.map"), "--rom", str(rom),
                        "--out", str(a.out)], check=True)
    lines = ['# Generated by tools/import_tmc_symbols/import_eu_symbols.py; metadata only.',
             '[program]', 'name = "The Legend of Zelda: The Minish Cap (Europe)"',
             'id = "minishcap_eu"', 'load_address = 0x08000000', 'size = 0x01000000',
             'entry_pc = 0x08000000', 'codegen_shards = 32', '', '[identity]', f'sha1 = "{SHA1}"',
             '', '[[data_range]]', 'start = 0x08000004', 'end = 0x080000C0']
    def seed(address, mode, name):
        lines.extend(['', '[[extra_func]]', f'addr = 0x{address:08X}', f'mode = "{mode}"', f'name = "{name}"'])
    seed(0x08000000, "arm", "rom_header_start_vector")
    seed(0x080000C0, "arm", "crt0_start")
    for runtime, source, size, name in copies:
        lines.extend(['', '[[code_copy]]', f'runtime_start = 0x{runtime:08X}',
                      f'source_start = 0x{source:08X}', f'size = 0x{size:X}', f'name = "{name}"'])
        # Resolve the real mode from ELF mapping symbols; RAM linker labels
        # themselves are NOTYPE and carry no THUMB bit.
        for alias, (address, _) in sorted(names.items()):
            if not alias.startswith("ram_") or not runtime <= address < runtime + size:
                continue
            offset = address - runtime
            mode = mappings[starts[bisect.bisect_right(starts, source + offset) - 1]]
            if mode in {"a", "t"}:
                seed(address, "arm" if mode == "a" else "thumb", alias)
        # Every executable interval of the copied code can yield at a frame
        # boundary. Exclude literal pools using the same ELF's $d metadata.
        points = sorted({source, source + size} | {x for x in starts if source < x < source + size})
        for lo, hi in zip(points, points[1:]):
            mode = mappings[starts[bisect.bisect_right(starts, lo) - 1]]
            if mode not in {"a", "t"}:
                continue
            start, end = runtime + lo - source, runtime + hi - source
            seed(start, "arm" if mode == "a" else "thumb", f"ram_code_{start:08X}")
            lines.extend(['', '[[resume_range]]', f'start = 0x{start:08X}', f'end = 0x{end:08X}',
                          f'mode = "{"arm" if mode == "a" else "thumb"}"'])
    (a.out / "minishcap_eu.toml").write_text("\n".join(lines) + "\n")
    (a.out / "provenance.json").write_text(json.dumps({"repository": "https://github.com/zeldaret/tmc",
        "revision": revision, "region": "EU", "sha1": SHA1, "size": 16777216,
        "method": "byte-matching tmc_eu.gba; readelf symbols/sections and linker map"}, indent=2) + "\n")


if __name__ == "__main__":
    main()
